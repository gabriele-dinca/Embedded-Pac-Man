void drawPacMan(uint8_t x, uint8_t y, Theme_t theme, PacDirection_t dir) {
    int8_t i, j;

    for (i = 0; i < SPRITE_SIZE; i++) {
        for (j = 0; j < SPRITE_SIZE; j++) {
             if (pacManBitmap[dir][i][j] == 0) {
                 Graphics_setForegroundColor(&g_sContext, cellColors[theme][PACM].primary);
             } else {
                 Graphics_setForegroundColor(&g_sContext, cellColors[theme][PACM].secondary);
             }

             Graphics_drawPixel(&g_sContext,
                                y * SPRITE_SIZE + j,
                                x * SPRITE_SIZE + i);
        }
    }
}


void drawCell(uint8_t x, uint8_t y, Theme_t theme, CellType_t type) {
    int8_t i, j;

    for (i = 0; i < SPRITE_SIZE; i++) {
        for (j = 0; j < SPRITE_SIZE; j++) {
             if (bitmaps[type][i][j] == 0) {
                 Graphics_setForegroundColor(&g_sContext, cellColors[theme][type].primary);
             } else {
                 Graphics_setForegroundColor(&g_sContext, cellColors[theme][type].secondary);
             }

             Graphics_drawPixel(&g_sContext,
                                y * SPRITE_SIZE + j,
                                x * SPRITE_SIZE + i);
        }
    }
}







